//! Иконки трав, веществ, посуды, книг и снадобий (src/lore.rs). Рисуются так же,
//! как остальные иконки: простыми фигурами в координатах клеток.

use super::*;

const LEAF: Rgba = rgb(70, 128, 58);
const LEAF_DARK: Rgba = rgb(40, 82, 36);
const STEM: Rgba = rgb(88, 110, 52);
const ROOT: Rgba = rgb(150, 112, 70);
const ROOT_DARK: Rgba = rgb(96, 66, 38);
const CLAY: Rgba = rgb(178, 98, 58);
const CLAY_DARK: Rgba = rgb(122, 62, 34);
const COPPER: Rgba = rgb(196, 112, 60);
const COPPER_DARK: Rgba = rgb(130, 68, 34);
const PAPYRUS: Rgba = rgb(222, 200, 150);
const PAPYRUS_DARK: Rgba = rgb(170, 140, 92);
const INK: Rgba = rgb(40, 32, 30);
const PARCHMENT_COVER: Rgba = rgb(110, 44, 36);
const STONE: Rgba = rgb(160, 156, 148);
const STONE_DARK: Rgba = rgb(104, 100, 94);

/// Веточка с листьями и цветками.
fn sprig(c: &mut Canvas, flower: Rgba) {
    c.line(0.5, 0.92, 0.5, 0.2, 0.05, STEM);
    for (i, y) in [0.75, 0.58, 0.42].into_iter().enumerate() {
        let s = if i % 2 == 0 { 1.0 } else { -1.0 };
        c.poly(&[(0.5, y), (0.5 + s * 0.32, y - 0.12), (0.5 + s * 0.12, y + 0.05)], LEAF);
        c.poly(&[(0.5, y), (0.5 - s * 0.28, y - 0.08), (0.5 - s * 0.1, y + 0.06)], LEAF_DARK);
    }
    for (x, y) in [(0.5, 0.16), (0.38, 0.24), (0.62, 0.24), (0.45, 0.3), (0.56, 0.12)] {
        c.circle(x, y, 0.07, flower);
    }
}

/// Широкие листья (подорожник, просвирник, вайда).
fn broad_leaves(c: &mut Canvas, color: Rgba) {
    for (a, len) in [(-0.6f32, 0.38), (0.0, 0.42), (0.6, 0.38), (2.6, 0.3), (3.7, 0.3)] {
        let (dx, dy) = (a.sin(), -a.cos());
        let tip = (0.5 + dx * len, 0.62 + dy * len);
        let side = (dy * 0.12, -dx * 0.12);
        c.poly(&[(0.5, 0.62), (0.5 + dx * len * 0.5 + side.0, 0.62 + dy * len * 0.5 + side.1), tip, (0.5 + dx * len * 0.5 - side.0, 0.62 + dy * len * 0.5 - side.1)], color);
        c.line(0.5, 0.62, tip.0, tip.1, 0.02, LEAF_DARK);
    }
}

fn root(c: &mut Canvas, body: Rgba, dark: Rgba) {
    c.poly(&[(0.42, 0.12), (0.6, 0.15), (0.66, 0.5), (0.55, 0.88), (0.45, 0.88), (0.36, 0.5)], body);
    c.line(0.52, 0.2, 0.5, 0.85, 0.04, dark);
    c.line(0.4, 0.45, 0.18, 0.62, 0.035, body);
    c.line(0.62, 0.55, 0.85, 0.72, 0.035, body);
    c.line(0.48, 0.12, 0.42, 0.02, 0.05, LEAF);
    c.line(0.54, 0.12, 0.62, 0.03, 0.05, LEAF);
}

fn berries(c: &mut Canvas, color: Rgba, light: Rgba) {
    c.line(0.3, 0.2, 0.7, 0.8, 0.03, WOOD_DARK);
    for (x, y) in [(0.36, 0.42), (0.55, 0.38), (0.48, 0.58), (0.66, 0.6), (0.4, 0.72), (0.58, 0.78)] {
        c.circle(x, y, 0.11, color);
        c.circle(x - 0.03, y - 0.03, 0.035, light);
    }
}

/// Комочки смолы или кристаллы.
fn lumps(c: &mut Canvas, color: Rgba, light: Rgba, angular: bool) {
    for (x, y, r) in [(0.35, 0.6, 0.17), (0.62, 0.64, 0.15), (0.5, 0.38, 0.15)] {
        if angular {
            c.poly(&[(x - r, y), (x - r * 0.4, y - r), (x + r * 0.6, y - r * 0.8), (x + r, y + r * 0.2), (x + r * 0.2, y + r)], color);
            c.poly(&[(x - r * 0.4, y - r), (x + r * 0.6, y - r * 0.8), (x, y)], light);
        } else {
            c.circle(x, y, r, color);
            c.circle(x - r * 0.35, y - r * 0.35, r * 0.35, light);
        }
    }
}

/// Горка порошка на черепке.
fn powder(c: &mut Canvas, color: Rgba, light: Rgba) {
    c.poly(&[(0.1, 0.8), (0.9, 0.8), (0.8, 0.9), (0.2, 0.9)], CLAY_DARK);
    c.poly(&[(0.16, 0.8), (0.5, 0.32), (0.84, 0.8)], color);
    c.poly(&[(0.5, 0.32), (0.84, 0.8), (0.6, 0.8)], light);
}

/// Флакон с жидкостью (холст 1×2 или 1×1).
fn vial(c: &mut Canvas, liquid: Rgba, tall: bool) {
    let (top, bottom) = if tall { (0.15, 1.85) } else { (0.1, 0.9) };
    let h = bottom - top;
    c.rect(0.42, top, 0.58, top + h * 0.1, WOOD);
    c.rect(0.44, top + h * 0.1, 0.56, top + h * 0.3, GLASS);
    c.circle(0.5, bottom - h * 0.3, h * 0.28, GLASS);
    c.circle(0.5, bottom - h * 0.27, h * 0.24, liquid);
    c.circle(0.42, bottom - h * 0.36, h * 0.06, [1.0, 1.0, 1.0, 0.5]);
}

/// Глиняный кувшин (вино, масло).
fn jug(c: &mut Canvas, mark: Rgba) {
    c.poly(&[(0.38, 0.2), (0.62, 0.2), (0.6, 0.45), (0.85, 0.9), (0.78, 1.65), (0.5, 1.85), (0.22, 1.65), (0.15, 0.9), (0.4, 0.45)], CLAY);
    c.poly(&[(0.5, 0.2), (0.62, 0.2), (0.6, 0.45), (0.85, 0.9), (0.78, 1.65), (0.5, 1.85)], CLAY_DARK);
    c.line(0.6, 0.35, 0.82, 0.7, 0.05, CLAY_DARK);
    c.rect(0.25, 1.05, 0.75, 1.15, mark);
}

fn scroll(c: &mut Canvas, seal: Rgba) {
    c.rect(0.28, 0.25, 0.72, 1.75, PAPYRUS);
    c.rect(0.56, 0.25, 0.72, 1.75, PAPYRUS_DARK);
    c.circle(0.5, 0.25, 0.22, PAPYRUS_DARK);
    c.circle(0.5, 1.75, 0.22, PAPYRUS_DARK);
    c.circle(0.5, 0.25, 0.08, WOOD_DARK);
    c.circle(0.5, 1.75, 0.08, WOOD_DARK);
    c.rect(0.25, 0.95, 0.75, 1.05, seal);
}

fn codex(c: &mut Canvas, cover: Rgba, ornament: Rgba) {
    c.rect(0.3, 0.25, 1.75, 1.8, PAPYRUS);
    c.rect(0.2, 0.15, 1.7, 1.75, cover);
    c.rect(0.2, 0.15, 0.36, 1.75, OUTLINE);
    c.ring(0.98, 0.95, 0.3, 0.38, ornament);
    c.poly(&[(0.98, 0.62), (1.08, 0.95), (0.98, 1.28), (0.88, 0.95)], ornament);
    for (x, y) in [(0.5, 0.35), (1.5, 0.35), (0.5, 1.55), (1.5, 1.55)] {
        c.circle(x, y, 0.06, ornament);
    }
}

fn fragment(c: &mut Canvas) {
    c.poly(&[(0.15, 0.2), (0.7, 0.12), (0.85, 0.45), (0.78, 0.85), (0.3, 0.9), (0.2, 0.6)], PAPYRUS);
    for y in [0.35, 0.48, 0.61, 0.74] {
        c.line(0.28, y, 0.7, y - 0.02, 0.025, INK);
    }
    c.poly(&[(0.7, 0.12), (0.85, 0.45), (0.65, 0.3)], PAPYRUS_DARK);
}

fn small_pot(c: &mut Canvas, fill: Rgba) {
    c.poly(&[(0.22, 0.4), (0.78, 0.4), (0.82, 0.85), (0.18, 0.85)], CLAY);
    c.rect(0.18, 0.32, 0.82, 0.42, CLAY_DARK);
    c.circle(0.5, 0.35, 0.22, fill);
}

