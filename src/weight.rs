/// Вес одной штуки (кг).
pub fn unit_weight(base: ItemBaseId) -> f32 {
    let name = base.base().name;
    WEIGHTS.iter().find(|(n, _)| *n == name).map(|(_, w)| *w).unwrap_or_else(|| estimate(base))
}

/// Оценка веса предмета, которого нет в таблице: по виду и числу клеток.
pub fn estimate(base: ItemBaseId) -> f32 {
    let info = base.base();
    let cells = (info.size.0 as f32 * info.size.1 as f32).max(1.0);
    match info.shape {
        ItemShape::Blade => 0.4 * cells,
        ItemShape::Blunt => 0.7 * cells,
        ItemShape::Polearm => 0.45 * cells,
        ItemShape::Shield => 0.9 * cells,
        ItemShape::Armor => 1.2 * cells,
        ItemShape::Helmet => 0.45 * cells,
        ItemShape::Coins => 0.006,
        ItemShape::Flask => 0.3 * cells,
        ItemShape::Small => 0.12 * cells,
    }
}

/// Вес стопки.
pub fn item_weight(item: &Item) -> f32 {
    unit_weight(item.base) * item.count.max(1) as f32
}

/// Всё, что на персонаже: надетое и в сумке.
pub fn inventory_weight(inv: &Inventory) -> f32 {
    inv.all_items().map(item_weight).sum()
}

/// Сколько можно нести без помехи (кг): 35 кг плюс по килограмму за каждую единицу силы.
pub fn carry_capacity(strength: f32) -> f32 {
    35.0 + strength.max(-20.0)
}

/// Множитель скорости ходьбы от ноши: до `carry_capacity` — 1, к двойной — 0,6, дальше — 0,4.
pub fn encumbrance(weight: f32, capacity: f32) -> f32 {
    if weight <= capacity {
        return 1.0;
    }
    let over = (weight - capacity) / capacity.max(1.0);
    if over <= 1.0 { 1.0 - 0.4 * over } else { 0.4 }
}

/// Предметы без своего веса в таблице (для тестов).
#[allow(dead_code)]
pub fn unweighted_items() -> Vec<&'static str> {
    ITEM_BASES.iter().filter(|b| !WEIGHTS.iter().any(|(n, _)| *n == b.name)).map(|b| b.name).collect()
}

/// «1,2 кг», «350 г».
pub fn format_weight(kg: f32) -> String {
    if kg < 1.0 {
        let g = kg * 1000.0;
        if g < 10.0 { format!("{g:.1} г").replace('.', ",") } else { format!("{g:.0} г") }
    } else if kg < 10.0 {
        format!("{kg:.1} кг").replace('.', ",")
    } else {
        format!("{kg:.0} кг")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_names_exist_and_weights_are_sane() {
        for (name, w) in WEIGHTS {
            assert!(ItemBaseId::find(name).is_some(), "в таблице веса лишнее имя «{name}»");
            assert!(*w > 0.0 && *w < 60.0, "странный вес «{name}»: {w}");
        }
        // Всё, что было в игре к появлению веса, взвешено вручную.
        let missing = unweighted_items();
        for name in ["Спата", "Кольчуга", "Амфора вина", "Солид", "Шалфей", "Алембик", "Цельс. О медицине"] {
            assert!(!missing.contains(&name), "нет веса у «{name}»");
        }
        for b in 0..ITEM_BASES.len() {
            assert!(unit_weight(ItemBaseId(b as u16)) > 0.0);
        }
    }

    #[test]
    fn realistic_relations() {
        let w = |n: &str| unit_weight(ItemBaseId::by_name(n));
        assert!(w("Ламеллярный панцирь") > w("Кольчуга"));
        assert!(w("Кольчуга") > w("Стёганая туника"));
        assert!(w("Амфора вина") > 10.0 * w("Кувшин вина"));
        assert!(w("Солид") < w("Фоллис"));
        assert!(w("Кинжал") < w("Спата"));
    }

    #[test]
    fn heavy_load_slows_down() {
        let cap = carry_capacity(0.0);
        assert_eq!(encumbrance(10.0, cap), 1.0);
        assert!(encumbrance(cap * 1.5, cap) < 0.85);
        assert!((encumbrance(cap * 5.0, cap) - 0.4).abs() < 1e-6);
        assert_eq!(format_weight(1.25), "1,2 кг");
        assert_eq!(format_weight(0.35), "350 г");
    }
}
