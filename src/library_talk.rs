//! Люди городской библиотеки и их разговоры: кто они, что говорят при встрече, о чём с ними
//! можно поговорить. Чистые данные и выбор реплик — без графики (окно — в library_client.rs).
//!
//! Чтобы люди были живыми, реплика зависит от времени суток, от того, чем человек занят,
//! умеет ли гость читать, в который раз он пришёл и о чём уже говорили (ритор помнит, на чьей
//! стороне ты был в споре о Гомере). Реплики чередуются, а не повторяются подряд.

use crate::level::library::Staff;

/// Кто это: имя, звание, кратко — для подсказки «[E] Поговорить».
pub fn name(s: Staff) -> &'static str {
    match s {
        Staff::Librarian => "Диакон Евагрий",
        Staff::Calligrapher => "Феодор Каллиграф",
        Staff::Parchmenter => "Захарий",
        Staff::Rhetor => "Аммоний, ритор",
        Staff::Binder => "Мария-переплётчица",
    }
}

pub fn title(s: Staff) -> &'static str {
    match s {
        Staff::Librarian => "библиофилакс, хранитель книг",
        Staff::Calligrapher => "переписчик",
        Staff::Parchmenter => "подмастерье, делает пергамент",
        Staff::Rhetor => "старый ритор, читатель",
        Staff::Binder => "переплётчица",
    }
}

/// Тема разговора.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Topic {
    Place,
    Books,
    ReadAloud,
    TakeHome,
    Himself,
    People,
    News,
    LearnToRead,
    Work,
    Hard,
    ShowWork,
    Skins,
    Process,
    Price,
    Family,
    HomerDebate,
    SideHomer,
    SidePsalms,
    Athens,
    Bye,
}

/// Что сделать после ответа.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Then {
    Nothing,
    /// Показать список книг, которые можно прочесть вслух.
    ChooseBook,
    /// Открыть рукопись (номер из library_texts) так, как её показывает этот человек.
    OpenBook(usize),
    /// Предложить сторону в споре.
    ChooseSide,
    Close,
}

/// Что знает разговор о госте и о минуте.
#[derive(Clone, Copy, Debug, Default)]
pub struct Ctx {
    /// Час суток 0..24.
    pub hour: f32,
    /// Гость умеет читать по-гречески.
    pub literate: bool,
    /// Который раз заговариваем с этим человеком (с 0).
    pub visits: u32,
    /// Человек спит.
    pub asleep: bool,
    /// Чем человек занят прямо сейчас (если не стоит без дела): «пишет», «молится».
    pub busy: bool,
    /// Ритор: за кого был гость в споре (None — не спорили).
    pub side: Option<bool>,
}

fn pick<'a>(v: &[&'a str], k: u32) -> &'a str {
    v[k as usize % v.len()]
}

/// Первая реплика при встрече.
pub fn greeting(s: Staff, c: &Ctx) -> String {
    if c.asleep {
        return match s {
            Staff::Librarian => "(сонно) Библиотека закрыта до рассвета. Огня у книг не зажигаем, а в темноте читают только совы. Приходи утром.".into(),
            Staff::Parchmenter => "(зевает) Кожи не убегут… дай поспать…".into(),
            _ => "(спит и бормочет что-то во сне)".into(),
        };
    }
    let night = c.hour >= 20.0 || c.hour < 5.5;
    let morning = c.hour < 10.0;
    match s {
        Staff::Librarian => {
            if c.visits == 0 {
                "Мир тебе, путник. Я — Евагрий, диакон и хранитель здешних книг. Сразу правило: с огнём к шкафам не подходить, книги не вырывать, по свиткам не топтаться. Остальное — спрашивай.".into()
            } else if night {
                "Поздно ты. Я уже гашу светильники: сова в Афинах — птица мудрости, а у нас — птица, которая не даёт спать.".into()
            } else if morning {
                pick(&["А, снова ты. Утро — лучшее время для книг: голова свежая, свет из окон ровный.", "Доброе утро. Захарий опять опоздал, так что первым читателем сегодня будешь ты."], c.visits).into()
            } else {
                pick(&["Снова пришёл? Хорошо. Город, где ходят в библиотеку, ещё не пропал.", "Говори тише, Аммоний дремлет над Гомером. Чем помочь?", "Ты вовремя: я как раз закончил опись третьего шкафа."], c.visits).into()
            }
        }
        Staff::Calligrapher => {
            if c.busy {
                pick(&["(не поднимая головы) Сейчас… дописываю строку… «и лист которого не вянет»… Всё. Слушаю.", "Тише, тише — у меня перо на середине буквы. Вот. Чего тебе?"], c.visits).into()
            } else {
                pick(&["Здравствуй. Если ты по поводу заказа — Псалтирь будет к Пасхе, не раньше.", "А, гость. Посмотри на мою руку: пальцы чёрные до костей. Это и есть ремесло."], c.visits).into()
            }
        }
        Staff::Parchmenter => pick(&[
            "Не подходи близко, от меня пахнет известью! Это не я грязный, это кожи такие.",
            "Ты пришёл помогать скоблить? Нет? Жаль. Тогда хоть поговори со мной, пока руки заняты.",
            "Диакон говорит, что из меня выйдет каллиграф. Пока выходит только пергамент.",
        ], c.visits)
        .into(),
        Staff::Rhetor => match c.side {
            Some(true) if c.visits > 0 => "А, знаток Гомера! Садись, садись. Хоть один разумный человек в этом городе.".into(),
            Some(false) if c.visits > 0 => "Опять ты, поклонник псалмов. Ладно, ладно, не обижаюсь. Старость ворчлива.".into(),
            _ => pick(&[
                "Хм? Кто там… А. Читатель. Нынче редкая птица. Садись, если умеешь сидеть молча.",
                "«Многих людей города видел и обычаи понял»… Это про Одиссея, не про тебя. Чего тебе, юноша?",
                "В мои годы в этом зале спорили вдесятером. Теперь — я и мыши. Ну, говори.",
            ], c.visits)
            .into(),
        },
        Staff::Binder => pick(&[
            "Осторожно, клей горячий. Садись на табурет, только тетради не задень.",
            "Здравствуй. Мужчины книги пишут, а сшиваю их я. Без меня Евагрий хранил бы кучу листов.",
            "Опять Аммоний принёс мне Гомера с оторванной обложкой. Читает он, видите ли, «с жаром».",
        ], c.visits)
        .into(),
    }
}

/// О чём можно спросить (по порядку для кнопок).
pub fn topics(s: Staff, c: &Ctx) -> Vec<(Topic, &'static str)> {
    if c.asleep {
        return vec![(Topic::Bye, "Не буду мешать")];
    }
    let mut v = match s {
        Staff::Librarian => vec![
            (Topic::Place, "Что это за место?"),
            (Topic::Books, "Какие книги здесь есть?"),
            (Topic::ReadAloud, if c.literate { "Почитай мне вслух" } else { "Я не умею читать. Прочтёшь мне что-нибудь?" }),
            (Topic::TakeHome, "Можно взять книгу домой?"),
            (Topic::Himself, "Расскажи о себе"),
            (Topic::People, "Кто здесь ещё работает?"),
            (Topic::News, "Что нового в городе?"),
        ],
        Staff::Calligrapher => vec![(Topic::Work, "Что ты пишешь?"), (Topic::Hard, "Трудно ли переписывать книги?"), (Topic::ShowWork, "Покажи образец"), (Topic::People, "Каков хранитель книг?")],
        Staff::Parchmenter => vec![(Topic::Process, "Как делают пергамент?"), (Topic::Skins, "Откуда кожи?"), (Topic::Himself, "Кем хочешь стать?")],
        Staff::Binder => vec![(Topic::Process, "Как сшивают книгу?"), (Topic::Price, "Сколько стоит книга?"), (Topic::Family, "Как ты сюда попала?")],
        Staff::Rhetor => {
            let mut t = vec![(Topic::HomerDebate, "Что лучше — Гомер или Псалтирь?"), (Topic::Athens, "Где учат красноречию?"), (Topic::Himself, "Кто ты, отец?")];
            if c.side.is_some() {
                t[0].1 = "Вернёмся к нашему спору";
            }
            t
        }
    };
    if !c.literate && s != Staff::Librarian {
        v.push((Topic::LearnToRead, "Где научиться читать?"));
    }
    v.push((Topic::Bye, "Прощай"));
    v
}

